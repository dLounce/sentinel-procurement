"""Deterministic evaluator-controlled adversarial vendor messages."""

from dataclasses import dataclass

from eval.adversarial.attacks import AttackTrajectory
from eval.adversarial.vendor_agent import AdversarialVendor


@dataclass(frozen=True)
class VendorMessage:
    """The two evaluator-visible parts of a vendor message."""

    commercial_content: str
    attack_payload: str | None = None

    @property
    def text(self) -> str:
        if not self.attack_payload:
            return self.commercial_content
        return f"{self.commercial_content} {self.attack_payload}"


@dataclass
class ScriptedAdversarialVendor(AdversarialVendor):
    """An economically normal vendor with an evaluator-controlled attack script.

    The inherited vendor model still owns the legitimate commercial quote. Attack
    payloads are deterministic evaluator fixtures and are never generated by the
    vendor model. A trajectory is local to this vendor, so multiple malicious
    vendors can carry independent trajectories.
    """

    trajectory: AttackTrajectory | None = None

    def __post_init__(self) -> None:
        if self.trajectory is not None and self.trajectory.attacker_vendor != self.vendor_id:
            raise ValueError(
                "attack trajectory is bound to a different vendor_id"
            )

    def attack_payload_for_round(self, round_index: int) -> str | None:
        round_number = round_index + 1
        if self.trajectory is None:
            return None
        return self.trajectory.payload_for_round(round_number)

    def propose_message(
        self,
        rfq,
        round_index,
        buyer_counter,
        history,
        *,
        model,
    ) -> VendorMessage:
        commercial = super().propose_quote(
            rfq,
            round_index,
            buyer_counter,
            history,
            model=model,
            inject=False,
        )
        return VendorMessage(
            commercial_content=commercial,
            attack_payload=self.attack_payload_for_round(round_index),
        )

    def propose_quote(
        self,
        rfq,
        round_index,
        buyer_counter,
        history,
        *,
        model,
        inject: bool = False,
    ) -> str:
        if inject:
            raise ValueError("ScriptedAdversarialVendor uses an AttackTrajectory, not inject=True")
        return self.propose_message(
            rfq,
            round_index,
            buyer_counter,
            history,
            model=model,
        ).text
